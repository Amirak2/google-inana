import assert from 'node:assert/strict';
import { Store } from '../server/storage.ts';
import { createAuthStore } from '../server/authStore.ts';
import { createApp } from '../server.ts';
const env = { SESSION_SECRET: 'auth-security-test-secret-longer-than-32', NODE_ENV: 'test' };
const store = new Store(env);
const auth = createAuthStore(store, env);
const app = createApp(store, env);
const mobile = '09120000811';
store.set('otp', mobile, { code: '12345', attempts: 0, expiresAt: Date.now() + 180000 });
const buyer = auth.verifySmsOtpAndAuthenticate(mobile, '12345');
assert.equal(buyer.user.role, 'customer');
assert.equal(auth.verifySessionToken(buyer.token).uid, buyer.user.uid);
const [payload, signature] = buyer.token.split('.');
const decoded = JSON.parse(Buffer.from(payload, 'base64url').toString()); decoded.uid = 'ina_admin_master';
assert.equal(auth.verifySessionToken(`${Buffer.from(JSON.stringify(decoded)).toString('base64url')}.${signature}`), null);
assert.equal(auth.verifySessionToken(`${payload}.invalid-signature`), null);
async function request(path, method = 'GET', body, token = buyer.token) {
  return app.fetch(new Request(`http://localhost${path}`, { method, headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) }));
}
assert.equal((await request('/api/admin/logs')).status, 403);
assert.equal((await request('/api/auth/profile', 'PUT', { displayName: 'Customer', role: 'admin' })).status, 200);
assert.equal((await request('/api/auth/me')).status, 200);
assert.equal(auth.findUserByMobile(mobile).role, 'customer');
assert.equal((await request('/api/auth/profile', 'PUT', { phoneNumber: '09128481806' })).status, 400);
assert.equal(auth.findUserByMobile(mobile).phoneNumber, mobile);
for (const path of ['/api/auth/login', '/api/auth/register', '/api/auth/google', '/api/auth/password/login', '/api/auth/password/set']) assert.equal((await request(path, 'POST', {})).status, 404);
assert.equal((await request('/api/auth/logout', 'POST', {})).status, 200);
assert.equal((await request('/api/auth/me')).status, 401);
