import assert from 'node:assert/strict';
import sharp from 'sharp';
import { installFakePostgres } from './fake-postgres.mjs';
import { PostgresStore } from '../server/postgresStorage.ts';
import { runPostgresRequest, requestBuckets } from '../server/postgresRequest.ts';
import { createApp } from '../server.ts';
import { createAuthStore } from '../server/authStore.ts';
import { ORDER_SHIPPING_NOTE } from '../src/utils/orderNotifications.ts';

process.env.PG_URI = 'postgresql://unused/notifications-test';
const db = installFakePostgres();
const env = { SESSION_SECRET: 'isolated-notifications-secret-longer-than-32', NODE_ENV: 'test' };
const deps = { externalize: async () => new Map(), migrate: async () => {} };
const seed = await PostgresStore.load(true);
seed.set('market', 'gold', { pricePerGram: 23932462, isManualOverride: true });
createApp(seed, env);
const auth = createAuthStore(seed, env);
const admin = [...seed.map('users').values()].find(u => u.role === 'admin');
const buyer = { uid: 'notification-buyer', email: 'buyer@local.test', phoneNumber: '09120000001', role: 'customer', createdAt: new Date().toISOString() };
const other = { ...buyer, uid: 'notification-other', email: 'other@local.test', phoneNumber: '09120000002' };
for (const user of [buyer, other]) seed.set('users', user.email, user);
const adminToken = auth.createSessionToken(admin), buyerToken = auth.createSessionToken(buyer), otherToken = auth.createSessionToken(other);
const product = [...seed.map('products').values()].find(p => p.pricingMode === 'fixed');
product.stock = 3;
await seed.commit(); await seed.release();
const receipt = 'data:image/png;base64,' + (await sharp({ create: { width: 128, height: 128, channels: 3, background: '#888888' } }).png().toBuffer()).toString('base64');
async function request(path, method = 'GET', body, token = buyerToken) {
  const req = new Request(`http://localhost${path}`, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
  const response = await runPostgresRequest(method, path, env, (store, requestEnv) => createApp(store, requestEnv).fetch(req.clone(), { clientIp: '198.51.100.31' }), deps);
  return { status: response.status, body: await response.json() };
}
assert.ok(requestBuckets('/api/notifications').includes('orders'));
assert.ok(requestBuckets('/api/notifications/read').includes('notificationReads'));
for (const [route, method] of [['/api/notifications', 'GET'], ['/api/notifications/read', 'POST']]) assert.equal((await request(route, method, method === 'POST' ? { all: true } : undefined, '')).status, 401);
const checkout = { customerName: 'مشتری تست', customerPhone: buyer.phoneNumber, customerAddress: 'تهران خیابان آزمایشی پلاک یک', items: [{ productId: product.id, quantity: 1 }], idempotencyKey: 'notification-checkout-1', paymentReceiptImage: receipt };
assert.equal((await request('/api/orders', 'POST', { ...checkout, paymentReceiptImage: '' })).status, 400);
assert.equal((await request('/api/notifications')).body.total, 0, 'Failed order never generates a notification');
const placed = await request('/api/orders', 'POST', checkout);
assert.equal(placed.status, 201, JSON.stringify(placed.body));
const order = placed.body.order;
assert.equal((await request('/api/orders', 'POST', checkout)).status, 200);
let feed = (await request('/api/notifications')).body;
assert.equal(feed.total, 1, 'Idempotent checkout creates exactly one notification');
assert.equal(feed.unreadCount, 1);
assert.match(feed.notifications[0].message, /در انتظار بررسی/);
assert.ok(feed.notifications[0].message.includes(ORDER_SHIPPING_NOTE));
assert.equal(feed.orders[0].status, 'در انتظار بررسی');
assert.equal(feed.orders[0].customerAddress, undefined);
assert.equal((await request('/api/notifications', 'GET', undefined, otherToken)).body.total, 0);
assert.equal((await request('/api/notifications', 'GET', undefined, adminToken)).body.total, 0, 'Admins see only their own notification inbox');
const route = `/api/orders/${order.id}/status`;
assert.equal((await request(route, 'PATCH', { status: 'تأیید شده' })).status, 403);
assert.equal((await request(route, 'PATCH', { status: 'تأیید شده' }, adminToken)).status, 200);
feed = (await request('/api/notifications')).body;
assert.equal(feed.total, 2);
const approved = feed.notifications.find(n => n.status === 'تأیید شده');
assert.ok(approved.message.includes('تأیید سفارش شما انجام شد'));
assert.ok(approved.message.includes(ORDER_SHIPPING_NOTE));
assert.equal(feed.orders[0].status, 'تأیید شده');
assert.equal((await request(route, 'PATCH', { status: 'تایید شده' }, adminToken)).status, 200);
assert.equal((await request('/api/notifications')).body.total, 2, 'Repeated approval does not duplicate notification');
assert.equal((await request('/api/notifications/read', 'POST', { ids: [approved.id] }, otherToken)).status, 404);
assert.equal((await request('/api/notifications')).body.unreadCount, 2, 'Another user cannot mark buyer notifications as read');
assert.equal((await request('/api/notifications/read', 'POST', { ids: [approved.id, 'someone-elses-id'] })).status, 404);
assert.equal((await request('/api/notifications')).body.unreadCount, 2, 'Mixed unauthorized IDs produce no partial write');
for (const body of [{}, { ids: [] }, { ids: [null] }, { ids: Array(101).fill('x') }, { all: true, ids: [] }]) assert.equal((await request('/api/notifications/read', 'POST', body)).status, 400);
assert.equal((await request('/api/notifications/read', 'POST', { ids: [approved.id] })).body.unreadCount, 1);
assert.equal((await request('/api/notifications')).body.unreadCount, 1, 'Read state persists across fresh PostgreSQL snapshots');
await request('/api/notifications/read', 'POST', { all: true });
assert.equal((await request('/api/notifications')).body.unreadCount, 0);
await request(route, 'PATCH', { status: 'در حال آماده‌سازی' }, adminToken);
assert.equal((await request('/api/notifications')).body.unreadCount, 1, 'New status remains unread after previous mark-all');
await request(route, 'PATCH', { status: 'ارسال شد' }, adminToken);
assert.equal((await request('/api/notifications')).body.orders[0].status, 'ارسال شد');
const existing = { ...order, id: 'preexisting-order', trackingCode: 'INA-OLD', status: 'تأیید شده' };
db.set('orders', existing.id, existing);
feed = (await request('/api/notifications')).body;
const oldNotice = feed.notifications.find(n => n.orderId === existing.id);
assert.ok(oldNotice.message.includes(ORDER_SHIPPING_NOTE), 'Existing customers receive a current status summary');
await request('/api/notifications/read', 'POST', { ids: [oldNotice.id] });
assert.ok((await request('/api/notifications')).body.notifications.find(n => n.id === oldNotice.id).readAt);
const publicStore = await PostgresStore.load(false, true);
assert.equal(publicStore.map('notifications').size, 0);
assert.equal(publicStore.map('notificationReads').size, 0);
await publicStore.release();
const before = (await request('/api/notifications')).body.total;
db.failNext('INSERT INTO site_records');
await assert.rejects(request(route, 'PATCH', { status: 'تکمیل شده' }, adminToken));
assert.equal(db.get('orders', order.id).status, 'ارسال شد');
assert.equal((await request('/api/notifications')).body.total, before, 'Failed commit rolls back order and notification together');
db.restore();
console.log('PASS: order submission/approval/status notifications, Monday shipping text, ownership, durable read state, existing-order fallback, idempotency and atomic PostgreSQL rollback. No live data or messages used.');
