import assert from 'node:assert/strict';
import { INITIAL_PRODUCTS } from '../src/data/seedData.ts';
import { DEFAULT_SETTINGS } from '../src/utils/pricingEngine.ts';
import { DEFAULT_CATALOG_FILTERS, normalizeCatalogFilters, normalizeCatalogText, filterCatalogProducts, sortCatalogProducts, catalogCategoryCounts, catalogWeightBounds } from '../src/utils/catalogFilters.ts';
import { buildSiteRoute, parseSiteRoute } from '../src/utils/siteRoutes.ts';
const products = INITIAL_PRODUCTS.filter(product => product.letter || product.pricingMode === 'fixed');
const filters = { ...DEFAULT_CATALOG_FILTERS };
assert.equal(filterCatalogProducts(products, {...filters, searchQuery: 'مروارید'}).length, 3);
assert.equal(filterCatalogProducts(products, {...filters, searchQuery: 'مرواريد'}).length, 3);
assert.equal(normalizeCatalogText('كیـــفِیت ۸'), normalizeCatalogText('کیفیت 8'));
const pearls = {...filters, selectedCollection: 'INANA PEARLS'};
const counts = catalogCategoryCounts(products, pearls);
assert.equal(counts.get('حروف انگلیسی') || 0, 0);
assert.equal([...counts.values()].reduce((a,b) => a+b, 0), 3);
assert.equal(catalogWeightBounds(products, pearls), null, 'Fixed price pearls must not set the gold weight range');
const gold = {...filters, selectedCategory: 'حروف انگلیسی'};
const range = catalogWeightBounds(products, gold);
assert.ok(range.min <= 0.26 && range.max >= 0.38 && range.step <= 0.01);
const light = filterCatalogProducts(products, {...gold, maxWeight: 0.3});
assert.deepEqual(light.map(product => product.letter).sort(), ['A', 'F']);
const heavy = {...products.find(product => product.letter === 'M'), id: 'local-heavy', weight: 12};
assert.ok(filterCatalogProducts([...products, heavy], filters).includes(heavy), 'Unlimited default must include 12g products');
assert.ok(!filterCatalogProducts([...products, heavy], {...filters, maxWeight: 10}).includes(heavy));
assert.equal(catalogWeightBounds([...products, heavy], gold).max, 12);
assert.equal(normalizeCatalogFilters({...gold, selectedLetter: 'a'}).selectedLetter, 'A');
assert.equal(normalizeCatalogFilters({...filters, selectedLetter: 'A'}).selectedLetter, null, 'Hidden letter filters must not survive unrelated catalog contexts');
assert.deepEqual(normalizeCatalogFilters({maxWeight: NaN, sortBy: 'invalid', selectedLetter: '<script>', onlyInStock: 'true'}), filters);
const reserved = {...heavy, stock: 2, availableStock: 0};
assert.equal(filterCatalogProducts([reserved], {...filters, onlyInStock: true}).length, 0);
const state = {...gold, selectedCollection: 'INANA LETTERS', searchQuery: 'پلاک', selectedLetter: 'A', maxWeight: 0.3, onlyInStock: true, sortBy: 'price-desc', activeTab: 'shop', quickViewProductId: null};
const url = new URL(buildSiteRoute(state), 'https://local.test');
assert.deepEqual(parseSiteRoute(url.pathname, url.search), state, 'Every filter must survive a shared link');
const sorted = sortCatalogProducts(products, 'weight-asc', 23932462, DEFAULT_SETTINGS);
assert.notEqual(sorted, products);
assert.ok(sorted.every((product, index) => !index || sorted[index-1].weight <= product.weight));
console.log('PASS: visible letter invariants, scoped category counts, sub-0.5g filtering, unlimited 12g stock, Persian/Arabic search and complete shared URLs.');
